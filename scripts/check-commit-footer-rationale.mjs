// CATALOG: INV-119 enforcement. Scans `origin/main..HEAD` commit range for commits that touch
// CATALOG:   suppression/bypass files (trivyignore, pitest-override). Verifies
// CATALOG:   each such commit carries a well-formed immutable commit-footer trailer from the set:
// CATALOG:   Suppression-Rationale, Pitest-Override-Rationale, Trivy-Expiry-Extension, Sigstore-Bypass.
// CATALOG: Rejected fold-in into check-suppression-rationale.mjs (that gate checks file content, not
// CATALOG:   commit history — different invariant axis). Hard-blocks (exit 1) on missing/malformed trailer.
// CATALOG: Writes evidence artifact to .arbiter/evidence/commit-footer-audit/<timestamp>.json (INV-evidence).
// CATALOG: #2669 — a commit only owes a trailer when its suppression-file hunks add an actual ENTRY
// CATALOG:   (added, non-blank, non-comment line; non-schema JSON key/item), decided from
// CATALOG:   `git show <hash> -- <path>` ADDED lines only (deletions/comments/schema never count).
// CATALOG:   Recognized trailers are also shape-validated per key (a parseable date/ref sub-field),
// CATALOG:   not just the `Key:` prefix.
// Exit codes per INV-53: 0=PASS, 1=FAIL, 2=ERROR
// Usage: node scripts/check-commit-footer-rationale.mjs [--range=<ref>] [--evidence-dir=<path>] [--dry-run] [--test-trailer=<value>] [--help]

import { execFileSync } from 'node:child_process'
import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve, join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const HELP = `Usage: node scripts/check-commit-footer-rationale.mjs [options]

Validates that commits touching suppression/bypass files in the git range carry
well-formed immutable commit-footer trailers (INV-119, §11.10(e)).

Options:
  --range=<ref>         Git range to scan (default: origin/main..HEAD)
  --evidence-dir=<path> Directory to write evidence artifact (default: .arbiter/evidence/commit-footer-audit/)
  --dry-run             Do not scan git history; validate --test-trailer value only
  --test-trailer=<val>  Validate a trailer string (for testing); use with --dry-run
  --test-path=<path>    Print whether a path is classified as a suppression file (for testing)
  --help, -h            Show this help and exit

Recognized footer trailers:
  Suppression-Rationale: <CVE-ID> | <justification> | expires:<YYYY-MM-DD>
  Pitest-Override-Rationale: <justification> | follow-up:<issue#> | approver:<handle>
  Trivy-Expiry-Extension: <CVE-ID> | new-expiry:<YYYY-MM-DD> | reason:<text>
  Sigstore-Bypass: <reason> | retry-after:<YYYY-MM-DD>

Suppression-touching files (patterns):
  *.trivyignore  *pitest*override*  suppressions/**
  (excludes EJS templates under src/templates/ — schema templates, not active waivers)

A trailer is only owed when a commit's hunks ADD a suppression entry — an empty
scaffold, a comment-only or schema-only edit needs no trailer (#2669).`

// Recognized trailer keys
const RECOGNIZED_TRAILERS = [
  'Suppression-Rationale',
  'Pitest-Override-Rationale',
  'Trivy-Expiry-Extension',
  'Sigstore-Bypass',
]

// Files whose presence in a commit requires a footer trailer
const SUPPRESSION_FILE_PATTERNS = [
  /\.trivyignore$/,
  /pitest.*override/i,
  /sigstore.*bypass/i,
  /^suppressions\//,
  /\/suppressions\//,
]

// EJS templates under src/templates/ are emitted into target projects — they define the
// *shape* of suppression artifacts (e.g. suppressions-schema.json.ejs), they are not
// arbiter's own active security waivers. A real waiver requiring rationale lives in the
// top-level `suppressions/` tree (still matched by /^suppressions\//). Editing a schema
// template must not demand a Suppression-Rationale footer.
const TEMPLATE_SOURCE_PREFIX = /(^|\/)src\/templates\//

// #1840 F4 tranche 4 (examples/ viventi): examples/{ts,python,go}-library/ are `arbiter
// init` OUTPUT committed for the living-examples showcase, regenerated by
// scripts/regenerate-examples.mjs — the RENDERED counterpart of the src/templates/ case
// above (same reasoning: a downstream project's own suppressions/ scaffolding is not
// arbiter's own active security waiver). A real waiver still lives at the top-level
// `suppressions/` tree, untouched by this exemption.
const GENERATED_EXAMPLE_PREFIX = /(^|\/)examples\/(ts|python|go)-library\//

/**
 * Check if a file path touches suppression artifacts.
 */
function isSuppressionFile(filePath) {
  if (TEMPLATE_SOURCE_PREFIX.test(filePath) && /\.ejs$/.test(filePath)) return false
  if (GENERATED_EXAMPLE_PREFIX.test(filePath)) return false
  return SUPPRESSION_FILE_PATTERNS.some((pat) => pat.test(filePath))
}

/**
 * Check if a trailer string is a recognized footer format.
 */
function isRecognizedTrailer(trailer) {
  if (!trailer || !trailer.trim()) return false
  return RECOGNIZED_TRAILERS.some((key) => trailer.trim().startsWith(key + ':'))
}

// AC3: the `Key:` prefix alone is not enough — each trailer key demands a parseable
// date (or a follow-up ref, for Pitest-Override-Rationale) in its own sub-field.
const TRAILER_SHAPE = {
  'Suppression-Rationale': { field: 'expires', kind: 'date' },
  'Trivy-Expiry-Extension': { field: 'new-expiry', kind: 'date' },
  'Sigstore-Bypass': { field: 'retry-after', kind: 'date' },
  'Pitest-Override-Rationale': { field: 'follow-up', kind: 'ref' },
}

function isValidDate(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false
  const d = new Date(`${value}T00:00:00Z`)
  if (Number.isNaN(d.getTime())) return false
  // #2669 finding 3: Date normalizes an impossible calendar date (2026-02-31 → 2026-03-03)
  // instead of rejecting it. Round-trip: reformat and require it to equal the input.
  return d.toISOString().slice(0, 10) === value
}

// #2669 finding 2: the `follow-up:` sub-field is documented as an issue reference
// (`follow-up:#9999`), not free text — `follow-up:garbage` must not validate.
function isValidRef(value) {
  return /^#?\d+$/.test(value)
}

/**
 * Validate the SHAPE of a trailer whose key is already recognized (AC3). Returns
 * `null` when valid, or a human-readable reason naming the missing/malformed part.
 */
function trailerShapeError(trailer) {
  const trimmed = trailer.trim()
  const key = RECOGNIZED_TRAILERS.find((k) => trimmed.startsWith(k + ':'))
  if (!key)
    return `trailer does not start with a recognized key (${RECOGNIZED_TRAILERS.join(', ')})`
  const shape = TRAILER_SHAPE[key]
  // #2669 finding 2: anchor to the `key:value` grammar — a bare substring match let
  // `not-expires:2099-01-01` satisfy the `expires:` field. Require the field name to
  // start at the beginning of the trailer or after whitespace/`|`, never mid-word.
  const match = new RegExp(`(?:^|[\\s|])${shape.field}:(\\S+)`).exec(trimmed)
  if (!match) return `${key} trailer is missing a "${shape.field}:" field`
  if (shape.kind === 'date' && !isValidDate(match[1])) {
    return `${key} trailer's "${shape.field}:${match[1]}" is not a valid YYYY-MM-DD date`
  }
  if (shape.kind === 'ref' && !isValidRef(match[1])) {
    return `${key} trailer's "${shape.field}:${match[1]}" is not a valid issue reference (expected #NNN)`
  }
  return null
}

/**
 * AC1: decide whether ADDED lines in a suppression-file hunk add an actual entry,
 * as opposed to only comments, schema boilerplate, or an empty scaffold. Kept
 * intentionally simple (#2669):
 *   - ignore-file style (.trivyignore, .gitleaksignore, any non-JSON suppression
 *     file): a blank line or a line starting with `#` doesn't count.
 *   - JSON allowlist style (path ends in .json): blank lines, pure JSON punctuation
 *     (`{`, `}`, `[`, `]`, trailing commas) and the `$schema`/`version` keys don't count.
 * Only ADDED lines are inspected — deletions never require a trailer.
 */
function addedLinesAddEntry(path, addedLines) {
  const isJson = /\.json$/.test(path)
  // #2669 finding 1 (round 2): the ARBITER-GENERATED schema-defining file
  // (suppressions/suppressions-schema.json, from suppressions-schema.json.ejs) declares
  // the SHAPE of suppression entries — it never contains one itself, no matter how many
  // of its own boilerplate keys ($id, title, description, type, items, definitions...)
  // get added. Matched by exact generated path only — NOT any `*-schema.json`, which
  // would let a real entry added to e.g. suppressions/custom-schema.json bypass the
  // footer. Keying on the two literal keys $schema/version (below) does not cover the
  // real generated file's shape.
  // #2669 finding 1 (round 3): exact equality, not a `(^|\/)...` regex — the regex
  // still matched a nested packages/api/suppressions/suppressions-schema.json, which
  // is not the root-level file this exemption is scoped to.
  if (isJson && path === 'suppressions/suppressions-schema.json') return false
  return addedLines.some((line) => {
    const trimmed = line.trim()
    if (!trimmed) return false
    if (isJson) {
      if (/^[{}[\],]*$/.test(trimmed)) return false
      if (/^"(\$schema|version)"\s*:/.test(trimmed)) return false
      return true
    }
    return !trimmed.startsWith('#')
  })
}

/**
 * Check whether commit `hash` adds a suppression ENTRY to `path` (AC1/AC2), via
 * `git show <hash> -- <path>` added lines. Fails safe (treats as entry-adding,
 * i.e. still demands a trailer) if the diff cannot be read.
 */
function commitAddsSuppressionEntry(hash, path, cwd) {
  let diff = ''
  try {
    diff = execFileSync('git', ['show', hash, '--format=', '--', path], {
      cwd,
      encoding: 'utf-8',
    })
  } catch {
    return true
  }
  const addedLines = diff
    .split('\n')
    .filter((line) => line.startsWith('+') && !line.startsWith('+++'))
    .map((line) => line.slice(1))
  return addedLinesAddEntry(path, addedLines)
}

/**
 * Parse CLI arguments.
 */
function parseArgs() {
  const raw = process.argv.slice(2)
  let range = 'origin/main..HEAD'
  let evidenceDir = join(SCRIPT_DIR, '.arbiter', 'evidence', 'commit-footer-audit')
  let dryRun = false
  let testTrailer = null
  let testPath = null
  let help = false

  for (let i = 0; i < raw.length; i++) {
    const arg = raw[i]
    if (arg === '--help' || arg === '-h') {
      help = true
    } else if (arg === '--dry-run') {
      dryRun = true
    } else if (arg.startsWith('--test-path=')) {
      testPath = arg.slice('--test-path='.length)
    } else if (arg === '--test-path' && i + 1 < raw.length) {
      testPath = raw[++i]
    } else if (arg.startsWith('--range=')) {
      range = arg.slice('--range='.length)
    } else if (arg === '--range' && i + 1 < raw.length) {
      range = raw[++i]
    } else if (arg.startsWith('--evidence-dir=')) {
      evidenceDir = resolve(arg.slice('--evidence-dir='.length))
    } else if (arg === '--evidence-dir' && i + 1 < raw.length) {
      evidenceDir = resolve(raw[++i])
    } else if (arg.startsWith('--test-trailer=')) {
      testTrailer = arg.slice('--test-trailer='.length)
    } else if (arg === '--test-trailer' && i + 1 < raw.length) {
      testTrailer = raw[++i]
    }
  }

  return { range, evidenceDir, dryRun, testTrailer, testPath, help }
}

/**
 * Get current git branch name. Returns 'unknown' on failure.
 */
function getCurrentBranch(cwd) {
  try {
    return execFileSync('git', ['branch', '--show-current'], {
      cwd,
      encoding: 'utf-8',
    }).trim()
  } catch {
    return 'unknown'
  }
}

/**
 * Run git log and return list of commits with their file changes and trailers.
 * Returns null if git command fails (origin/main unavailable).
 */
function getCommitsInRange(range, cwd) {
  try {
    // Get list of commit hashes in range
    const hashList = execFileSync('git', ['log', '--format=%H', range], {
      cwd,
      encoding: 'utf-8',
    })
      .trim()
      .split('\n')
      .filter(Boolean)

    if (hashList.length === 0) return []

    const commits = []
    for (const hash of hashList) {
      // Get commit body (full message with trailers)
      let body = ''
      try {
        body = execFileSync('git', ['log', '--format=%B', '-1', hash], {
          cwd,
          encoding: 'utf-8',
        }).trim()
      } catch {
        body = ''
      }

      // Get files changed by this commit
      let files = []
      try {
        const diffOutput = execFileSync(
          'git',
          ['diff-tree', '--no-commit-id', '-r', '--name-only', hash],
          { cwd, encoding: 'utf-8' },
        )
          .trim()
          .split('\n')
          .filter(Boolean)
        files = diffOutput
      } catch {
        files = []
      }

      // Extract trailers from commit body (lines that look like "Key: value")
      const trailers = body
        .split('\n')
        .filter((line) => /^[A-Z][A-Za-z-]+:\s/.test(line))
        .map((l) => l.trim())

      commits.push({ hash: hash.slice(0, 12), fullHash: hash, files, trailers, body })
    }

    return commits
  } catch {
    return null
  }
}

/**
 * Write evidence artifact JSON.
 */
function writeEvidence(evidenceDir, data) {
  try {
    mkdirSync(evidenceDir, { recursive: true })
    const ts = new Date().toISOString().replace(/[:.]/g, '-')
    const filePath = join(evidenceDir, `${ts}.json`)
    writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n')
  } catch (err) {
    process.stderr.write(
      `[commit-footer] WARN: could not write evidence artifact: ${err instanceof Error ? err.message : String(err)}\n`,
    )
  }
}

function main() {
  const { range, evidenceDir, dryRun, testTrailer, testPath, help } = parseArgs()

  if (help) {
    process.stdout.write(HELP + '\n')
    process.exit(0)
  }

  // --test-path mode: classify a single path (for tests); exit 0 regardless.
  if (testPath !== null) {
    process.stdout.write(
      isSuppressionFile(testPath) ? 'SUPPRESSION-FILE\n' : 'NOT-SUPPRESSION-FILE\n',
    )
    process.exit(0)
  }

  // --dry-run --test-trailer mode: validate a single trailer string
  if (dryRun && testTrailer !== null) {
    if (!isRecognizedTrailer(testTrailer)) {
      process.stderr.write(`[commit-footer] FOOTER-MISSING: trailer not recognized or empty\n`)
      process.exit(1)
    }
    const shapeError = trailerShapeError(testTrailer)
    if (shapeError) {
      process.stderr.write(`[commit-footer] FOOTER-MISSING: ${shapeError}\n`)
      process.exit(1)
    }
    process.stdout.write(`[commit-footer] VALID: trailer recognized\n`)
    process.exit(0)
  }

  if (dryRun) {
    process.stdout.write('[commit-footer] dry-run: no git history scanned\n')
    process.exit(0)
  }

  const cwd = process.cwd()
  const branch = getCurrentBranch(cwd)
  const commits = getCommitsInRange(range, cwd)

  if (commits === null) {
    // git log failed — origin/main is unavailable
    process.stderr.write(
      `[commit-footer] WARN: git log failed for range '${range}' — origin/main may be unavailable. Skipping check.\n`,
    )

    writeEvidence(evidenceDir, {
      schema: 'arbiter-commit-footer-audit-v1',
      generated_at: new Date().toISOString(),
      branch,
      range,
      commits_scanned: 0,
      commits_requiring_footer: 0,
      commits_with_valid_footer: 0,
      violations: [],
      result: 'SKIP',
      note: 'git log unavailable — origin/main unreachable',
    })

    process.exit(0)
  }

  const violations = []
  let commitsRequiringFooter = 0
  let commitsWithValidFooter = 0

  for (const commit of commits) {
    const suppressionFiles = commit.files.filter(isSuppressionFile)
    if (suppressionFiles.length === 0) continue

    // AC1: a commit whose suppression-file hunks add no ENTRY (only comments, schema,
    // empty scaffold, or deletions) does not owe a trailer.
    const addsEntry = suppressionFiles.some((f) =>
      commitAddsSuppressionEntry(commit.fullHash, f, cwd),
    )
    if (!addsEntry) continue

    commitsRequiringFooter++
    const recognizedTrailers = commit.trailers.filter(isRecognizedTrailer)
    const validTrailer = recognizedTrailers.find((t) => trailerShapeError(t) === null)

    if (validTrailer) {
      commitsWithValidFooter++
    } else {
      const shapeErrors = recognizedTrailers.map(trailerShapeError).filter(Boolean)
      const error =
        shapeErrors.length > 0
          ? shapeErrors.join('; ')
          : 'No recognized footer trailer found for suppression-touching commit'
      violations.push({
        commit: commit.hash,
        suppression_files: suppressionFiles,
        trailers_found: commit.trailers,
        error,
      })
      process.stderr.write(
        `[commit-footer] FOOTER-MISSING: commit ${commit.hash} touches suppression file(s) but has no recognized footer trailer\n`,
      )
      for (const f of suppressionFiles) {
        process.stderr.write(`  suppression file: ${f}\n`)
      }
      for (const e of shapeErrors) {
        process.stderr.write(`  ${e}\n`)
      }
      process.stderr.write(
        `  Required: Suppression-Rationale: / Pitest-Override-Rationale: / Trivy-Expiry-Extension: / Sigstore-Bypass:\n`,
      )
    }
  }

  const result = violations.length === 0 ? 'PASS' : 'FAIL'

  const evidence = {
    schema: 'arbiter-commit-footer-audit-v1',
    generated_at: new Date().toISOString(),
    branch,
    range,
    commits_scanned: commits.length,
    commits_requiring_footer: commitsRequiringFooter,
    commits_with_valid_footer: commitsWithValidFooter,
    violations,
    result,
  }

  writeEvidence(evidenceDir, evidence)

  if (violations.length > 0) {
    process.stderr.write(
      `[commit-footer] FAIL — ${violations.length} commit(s) missing required footer trailers\n`,
    )
    process.exit(1)
  }

  process.stdout.write(
    `[commit-footer] PASS — ${commits.length} commits scanned, ${commitsRequiringFooter} required footer, ${commitsWithValidFooter} validated\n`,
  )
  process.exit(0)
}

main()
