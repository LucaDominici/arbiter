//
// Archetype choice: `library`. It is the ONE archetype all three Generator
// Matrix DEEP cells (.github/workflows/generator-matrix.yml) actually exercise
// today — the TypeScript cell (packaged-artifact.test.ts) hardcodes the
// `ts-library` fixture; the Python/Go cells (`fixture-functional.test.ts -t
// <lang>`) vitest-name-filter-match every `tier: functional` fixture whose
// describe block contains the language, which today includes BOTH `<lang>-library`
// and the `backend-web-db` GA fixtures — so `library` is the common subset the
// matrix proves for ALL three, while `backend-web-db` is only proven for two.
// Keeping examples/ tied to the guaranteed-common cell keeps the "regenerated by
// the matrix, drift = red" claim honest rather than a superset of what actually runs.
//
// Determinism (the actual point of this file): a naive re-run is NOT byte-identical.
// Two problems, both fixed below:
//   1. `arbiter init` appends `.evidence/cmd-log.jsonl` (ts + durationMs + headSha —
//      see src/utils/evidence-log.ts) as a side effect of the invocation itself. This
//      is a runtime audit log, not generator OUTPUT, so `--no-evidence` (src/cli.ts)
//      is used to suppress it at the source rather than post-hoc-excluding it — the
//      same category of fix the bake harness already applies to the OTHER
//      host/run-dependent generated file, `.arbiter/detected-integrations.json`
//      (see __tests__/integration/e2e/helpers.ts EXCLUDE_RELS, #1685).
//   2. The staging directory's basename leaks into rendered docs (derived project
//      name). Pinned by always staging under a directory named after the fixture
//      (e.g. `ts-library`), never a random tmp-prefixed name.
//
// Usage:
//   node scripts/regenerate-examples.mjs                    # write examples/<name>/ in place
//   node scripts/regenerate-examples.mjs --check             # regenerate to tmp + diff; exit 1 on drift
//   node scripts/regenerate-examples.mjs --check --stack=go  # limit to one stack (CI matrix cell)

import { execFileSync, spawnSync } from 'node:child_process'
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '..')
const DIST_CLI = join(ROOT, 'dist', 'cli.js')
const FIXTURES_ROOT = join(ROOT, '__tests__', 'fixtures', 'real-projects')
const EXAMPLES_ROOT = join(ROOT, 'examples')

// Closed list (#1840 tranche-2 decision, 2026-07-09): TypeScript/Python/Go are the
// README's declared GA stacks. `library` is the archetype the Generator Matrix
// workflow's DEEP cells actually exercise for all three (see file header).
export const LIVING_EXAMPLES = [
  { name: 'ts-library', fixture: 'ts-library', language: 'typescript', archetype: 'library' },
  {
    name: 'python-library',
    fixture: 'python-library',
    language: 'python',
    archetype: 'library',
  },
  { name: 'go-library', fixture: 'go-library', language: 'go', archetype: 'library' },
]

// Fixture-only metadata that is not part of the real starter project a user would
// actually have on disk (arbiter's own test harness bookkeeping).
const FIXTURE_ONLY_FILES = new Set(['manifest.json'])

// #1685-class ENV-DERIVED output: `.arbiter/detected-integrations.json` is written
// only when `arbiter init` detects Claude skills installed under the CALLING
// MACHINE's $HOME/.claude — present on a dev host, absent in CI's clean env. There
// is no CLI flag to suppress the detection itself (unlike `.evidence/cmd-log.jsonl`
// and `--no-evidence` above), so this reuses the SAME exclusion the bake harness
// already applies for exactly this file (__tests__/integration/e2e/helpers.ts
// EXCLUDE_RELS, #1685) — deleted post-generation so the committed example
// represents the portable, host-independent output.
const POST_GENERATION_EXCLUDE_RELS = new Set(['.arbiter/detected-integrations.json'])

export function parseArgs(argv) {
  const check = argv.includes('--check')
  const stackArg = argv.find((a) => a.startsWith('--stack='))
  const stack = stackArg ? stackArg.slice('--stack='.length) : null
  return { check, stack }
}

function listFiles(dir) {
  const out = []
  const stack = [dir]
  while (stack.length > 0) {
    const current = stack.pop()
    for (const entry of readdirSync(current)) {
      if (entry === '.git') continue
      const full = join(current, entry)
      const st = statSync(full)
      if (st.isDirectory()) {
        stack.push(full)
      } else {
        out.push(relative(dir, full))
      }
    }
  }
  return out.sort()
}

/** Pure diff between two staged directory trees. Exported for unit testing. */
export function diffDirs(committedDir, freshDir) {
  const committed = new Set(existsSync(committedDir) ? listFiles(committedDir) : [])
  const fresh = new Set(listFiles(freshDir))
  const removed = [...committed].filter((f) => !fresh.has(f)).sort()
  const added = [...fresh].filter((f) => !committed.has(f)).sort()
  const changed = [...fresh]
    .filter((f) => committed.has(f))
    .filter((f) => {
      const a = readFileSync(join(committedDir, f))
      const b = readFileSync(join(freshDir, f))
      return !a.equals(b)
    })
    .sort()
  return { removed, added, changed }
}

function runGit(args, cwd) {
  execFileSync('git', args, { cwd, stdio: 'ignore' })
}

/**
 * Stage `example.fixture`, run a REAL `arbiter init` through the built dist/cli.js,
 * and return the resulting directory (caller owns cleanup of `parent`).
 */
function generateOne(example) {
  if (!existsSync(DIST_CLI)) {
    throw new Error(`dist/cli.js not found at ${DIST_CLI} — run \`npm run build\` first`)
  }
  const parent = mkdtempSync(join(tmpdir(), 'arbiter-examples-'))
  // Basename is pinned to the fixture name (not the tmp-prefixed parent) so the
  // directory-derived project name in rendered docs is stable across machines/runs.
  const stageDir = join(parent, example.name)
  cpSync(join(FIXTURES_ROOT, example.fixture), stageDir, { recursive: true })
  for (const f of FIXTURE_ONLY_FILES) {
    const p = join(stageDir, f)
    if (existsSync(p)) rmSync(p)
  }

  runGit(['init', '-q', '-b', 'main'], stageDir)
  // arbiter-suppress(INV-12, until=2099-01-01, reason="fixture email for the examples/ regenerate harness", owner=@luca)
  runGit(['config', 'user.email', 'arbiter-example@arbiter.dev'], stageDir)
  runGit(['config', 'user.name', 'Arbiter Example'], stageDir)
  runGit(['add', '-A'], stageDir)
  runGit(['commit', '-q', '-m', 'chore: starter', '--no-verify'], stageDir)

  // #1937 — HOST-PORTABLE OUTPUT: `arbiter init` derives claudeHome from
  // process.env.HOME (init.ts) and renders any detected `~/.claude` skills into
  // AGENTS.md's "Installed Skills" table (AGENTS.md.ejs). A dev host with plugins
  // installed would bake its LOCAL skills into the committed example, which then
  // drifts against CI's clean-env regeneration (Generator Matrix DEEP cell). Point
  // HOME at an empty dir so skill detection finds nothing — the same portable
  // output CI produces — regardless of the calling machine.
  const emptyHome = join(parent, '.empty-home')
  mkdirSync(emptyHome, { recursive: true })

  const r = spawnSync(
    process.execPath,
    [
      DIST_CLI,
      'init',
      '--yes',
      '--tools',
      'claude',
      '--level',
      'L1',
      '--no-verify',
      '--no-evidence',
      '--language',
      example.language,
      '--archetype',
      example.archetype,
    ],
    { cwd: stageDir, encoding: 'utf-8', env: { ...process.env, HOME: emptyHome } },
  )
  if (r.status !== 0) {
    rmSync(parent, { recursive: true, force: true })
    throw new Error(
      `arbiter init failed for ${example.name} (exit ${r.status}):\n${(r.stdout ?? '') + (r.stderr ?? '')}`,
    )
  }
  rmSync(join(stageDir, '.git'), { recursive: true, force: true })
  for (const rel of POST_GENERATION_EXCLUDE_RELS) {
    const p = join(stageDir, rel)
    if (existsSync(p)) rmSync(p)
  }
  return { parent, stageDir }
}

function main(argv) {
  const { check, stack } = parseArgs(argv)
  const examples = stack ? LIVING_EXAMPLES.filter((e) => e.language === stack) : LIVING_EXAMPLES
  if (examples.length === 0) {
    process.stderr.write(`  ERROR examples — no living example matches --stack=${stack}\n`)
    return 2
  }

  let drift = false
  for (const example of examples) {
    process.stdout.write(`  → ${example.name} (${example.language}/${example.archetype})\n`)
    const { parent, stageDir } = generateOne(example)
    try {
      const target = join(EXAMPLES_ROOT, example.name)
      if (check) {
        const { removed, added, changed } = diffDirs(target, stageDir)
        if (removed.length === 0 && added.length === 0 && changed.length === 0) {
          process.stdout.write(`    OK    no drift\n`)
          continue
        }
        drift = true
        process.stderr.write(`    FAIL  drift detected in examples/${example.name}/\n`)
        for (const f of removed) process.stderr.write(`      - removed: ${f}\n`)
        for (const f of added) process.stderr.write(`      - added:   ${f}\n`)
        for (const f of changed) process.stderr.write(`      - changed: ${f}\n`)
      } else {
        rmSync(target, { recursive: true, force: true })
        mkdirSync(target, { recursive: true })
        cpSync(stageDir, target, { recursive: true })
        process.stdout.write(`    wrote examples/${example.name}/\n`)
      }
    } finally {
      rmSync(parent, { recursive: true, force: true })
    }
  }

  if (check && drift) {
    process.stderr.write(
      `\n  examples/ has drifted from what \`arbiter init\` generates today.\n` +
        `  Run \`npm run examples:regenerate\` and commit the result.\n`,
    )
    return 1
  }
  process.stdout.write(check ? '\n  examples: no drift\n' : '\n  examples: regenerated\n')
  return 0
}

const isMain = process.argv[1] != null && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  try {
    process.exit(main(process.argv.slice(2)))
  } catch (err) {
    process.stderr.write(
      `  ERROR examples — ${err instanceof Error ? (err.stack ?? err.message) : String(err)}\n`,
    )
    process.exit(2)
  }
}
